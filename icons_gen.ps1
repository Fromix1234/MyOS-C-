# --- validate + encode -----------------------------------------------------
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// Generated by icons_gen.ps1 - do not edit by hand.')
[void]$sb.AppendLine('// 7 dock icons, 20x20 pixels, 1 bit each: 3 bytes per row (high bit = left pixel).')
[void]$sb.AppendLine('const unsigned char dock_icons[7][60] = {')
for ($k = 0; $k -lt 7; $k++) {
    $rows = $arts[$k]
    if ($rows.Count -ne $N) { throw "icon $k has $($rows.Count) rows, expected $N" }
    Write-Host ("--- {0} ---" -f $NAMES[$k])
    [void]$sb.AppendLine('  {   // ' + $NAMES[$k])
    foreach ($r in $rows) {
        if ($r.Length -ne $N) { throw "icon $k row [$r] has $($r.Length) chars, expected $N" }
        Write-Host ('  ' + $r)
        $b0 = 0; $b1 = 0; $b2 = 0
        for ($i = 0; $i -lt $N; $i++) {
            if ($r[$i] -ne 'X') { continue }
            $bit = 0x80 -shr ($i % 8)
            if ($i -lt 8)      { $b0 = $b0 -bor $bit }
            elseif ($i -lt 16) { $b1 = $b1 -bor $bit }
            else               { $b2 = $b2 -bor $bit }
        }
        [void]$sb.AppendLine(("    0x{0:X2}, 0x{1:X2}, 0x{2:X2}," -f $b0, $b1, $b2))
    }
    [void]$sb.AppendLine('  },')
}
[void]$sb.AppendLine('};')
[System.IO.File]::WriteAllText($OUT, $sb.ToString(), [System.Text.Encoding]::ASCII)
Write-Host ("written: {0} bytes" -f (Get-Item $OUT).Length)
