# --- 6: About - circle with "i" (generated with math so it is truly round) --
function New-AboutIcon {
    $rows = @()
    for ($y = 0; $y -lt $N; $y++) {
        $line = ''
        for ($x = 0; $x -lt $N; $x++) {
            $dx = 2 * $x - ($N - 1)
            $dy = 2 * $y - ($N - 1)
            $d2 = $dx * $dx + $dy * $dy
            $on = ($d2 -le 225 -and $d2 -ge 144)          # ring: r=7.5px, 1.5px thick
            if ($x -ge 9 -and $x -le 10 -and $y -ge 6  -and $y -le 7)  { $on = $true }  # dot
            if ($x -ge 9 -and $x -le 10 -and $y -ge 9  -and $y -le 13) { $on = $true }  # stem
            if ($on) { $line += 'X' } else { $line += '.' }
        }
        $rows += $line
    }
    return $rows
}
