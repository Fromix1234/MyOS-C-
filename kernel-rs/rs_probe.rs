// ===========================================================================
//  kernel-rs: ПРОТОТИП Rust-компонента ядра (ring 0, no_std)
// ===========================================================================
//  Собирается в COFF-объекты под i686-pc-windows-gnu, поэтому линкуется тем
//  же MinGW-линкером, что и C++-ядро (ld -m i386pe). Граница между языками —
//  обычный C ABI (extern "C"): никакой магии, как между модулями Linux.
//
//  Цель этого файла — доказать сборку и запуск: Rust-код живёт в ring 0 и
//  умеет звать C++ (k_puts -> системный лог + COM1).
// ===========================================================================

#![no_std]

use core::panic::PanicInfo;

// Паники в ядре не разматывают стек: аварийно останавливаемся (как panic=abort).
#[panic_handler]
fn panic(_info: &PanicInfo) -> ! {
    loop {
        core::hint::spin_loop();
    }
}

extern "C" {
    // Реализация в C++ (kernel/k0_io.cpp): печать в dmesg + COM1.
    fn k_puts(s: *const u8);
}

// Точка входа прототипа: ядро зовёт её из kernel_main.
#[no_mangle]
pub extern "C" fn rs_probe() {
    unsafe {
        k_puts(b"rust: online (ring 0, no_std, COFF)\n\0".as_ptr());
    }
}
