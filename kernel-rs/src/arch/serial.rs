use super::cpu;

const COM1: u16 = 0x3F8;

/// Настроить COM1: 38400 бод, 8N1, FIFO.
pub fn init() {
    unsafe {
        cpu::outb(COM1 + 1, 0x00); // без прерываний serial
        cpu::outb(COM1 + 3, 0x80); // DLAB: настраиваем делитель
        cpu::outb(COM1 + 0, 0x03); // 38400 бод
        cpu::outb(COM1 + 1, 0x00);
        cpu::outb(COM1 + 3, 0x03); // 8 бит, без чётности, 1 стоп-бит
        cpu::outb(COM1 + 2, 0xC7); // FIFO вкл, чистим
        cpu::outb(COM1 + 4, 0x0B); // DTR/RTS/OUT2
    }
}

/// Послать один байт (ждём, пока освободится регистр передачи).
pub fn putc(c: u8) {
    unsafe {
        for _ in 0..10000 {
            if cpu::inb(COM1 + 5) & 0x20 != 0 {
                break;
            }
        }
        cpu::outb(COM1, c);
    }
}

/// Послать строку байт.
pub fn write(bytes: &[u8]) {
    for &b in bytes {
        putc(b);
    }
}
