//  MyOS v3 — ЯДРО НА RUST (ring 0), новая архитектура с нуля
// ===========================================================================
//  Принципы:
//    * монолитное ядро, но с ЖЁСТКИМИ границами модулей (arch / drivers /
//      mem / fs / task / syscall) — каждый модуль прячет своё состояние;
//    * никаких общих переменных с оболочкой: только ABI системных вызовов
//      (common/myos.h) — оболочка осталась на C++ в ring 3;
//    * загрузчик (boot/vbr/stage2, NASM) не меняется: он грузит kernel.bin
//      по адресу 0x10000 и прыгает на kernel_main;
//    * unsafe — только в низкоуровневых модулях (порты, таблицы, MMIO),
//      логика же работает с безопасными типами.
//
//  Этот файл — точка входа и корень дерева модулей.
// ===========================================================================

#![no_std]
#![allow(static_mut_refs)]

use core::panic::PanicInfo;

mod arch;

/// Паника ядра: печатаем в COM1 и навсегда останавливаемся.
/// (Позже добавим экран ошибки и перезагрузку — как boot_error_screen.)
#[panic_handler]
fn panic(_info: &PanicInfo) -> ! {
    arch::serial::write(b"kernel panic: stopped\n");
    loop {
        unsafe { arch::cpu::halt() }
    }
}

/// Точка входа: stage2 прыгает сюда (ENTRY(_kernel_main) в kernel.ld).
/// Пока M0 — доказательство, что новое ядро грузится и говорит по COM1.
#[no_mangle]
pub extern "C" fn kernel_main() -> ! {
    arch::serial::init();
    arch::serial::write(b"rust kernel: start (M0)\n");
    loop {
        unsafe { arch::cpu::halt() }
    }
}
