//    s1d  — видео (SYS_FB), обои Night Ridge/Bliss, раскладка и рамка окна;
//    s2   — оконный менеджер (z-порядок, перетаскивание), таблица клавиш;
//    s3   — консоль: сетка символов, команды, курсор мыши;
//    s4   — прослойка: старые имена ядра через сисколлы + сбор ввода;
//    s5   — рабочий стол: меню-бар, часы, док, About;
//    s6   — приложения: Terminal/Files/Settings/Tasks;
//    s7   — игра «змейка»;
//    s8   — редактор MyC;
//    s9   — графический мастер установки;
//    s10  — диспетчер команд консоли;
//    s13  — Activities: обзор приложений (F2);
//    s11  — композитор: перерисовка окон, клики, фокус;
